-- Module 21 PostgreSQL publication persistence schema, migration 0001.
-- Additive schema; apply only on an isolated disposable test branch.
CREATE TABLE IF NOT EXISTS layer1_claim_verification_runs (
 verification_id TEXT PRIMARY KEY CHECK(length(verification_id)=64),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 claim_count INTEGER NOT NULL CHECK(claim_count >= 0),
 verified_count INTEGER NOT NULL CHECK(verified_count >= 0),
 corroborated_count INTEGER NOT NULL CHECK(corroborated_count >= 0),
 unresolved_count INTEGER NOT NULL CHECK(unresolved_count >= 0),
 payload_json JSONB NOT NULL CHECK(jsonb_typeof(payload_json)='object')
);
CREATE INDEX IF NOT EXISTS idx_layer1_claim_verification_latest
 ON layer1_claim_verification_runs(created_at DESC, verification_id DESC);
CREATE TABLE IF NOT EXISTS layer1_event_lifecycle (
 event_id TEXT PRIMARY KEY, asset_id TEXT NOT NULL, source_id TEXT NOT NULL, event_type TEXT NOT NULL,
 state TEXT NOT NULL CHECK(state IN ('DISCOVERED','UNDER_VERIFICATION','CONFIRMED','DEVELOPING','RESOLVED','STALE','DISPUTED','WITHDRAWN')),
 first_published_at TIMESTAMPTZ NOT NULL, first_observed_at TIMESTAMPTZ NOT NULL,
 last_updated_at TIMESTAMPTZ NOT NULL, effective_event_at TIMESTAMPTZ NOT NULL,
 latest_revision_hash TEXT NOT NULL, updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(length(btrim(asset_id))>0), CHECK(length(btrim(source_id))>0), CHECK(length(btrim(event_type))>0)
);
CREATE INDEX IF NOT EXISTS idx_layer1_event_state ON layer1_event_lifecycle(state,last_updated_at);
CREATE TABLE IF NOT EXISTS layer1_event_revisions (
 event_id TEXT NOT NULL REFERENCES layer1_event_lifecycle(event_id), revision_hash TEXT NOT NULL,
 source_published_at TIMESTAMPTZ NOT NULL, source_updated_at TIMESTAMPTZ,
 observed_at TIMESTAMPTZ NOT NULL, evidence_ref TEXT NOT NULL, payload_json JSONB NOT NULL,
 PRIMARY KEY(event_id,revision_hash)
);
CREATE TABLE IF NOT EXISTS layer1_event_transitions (
 transition_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id TEXT NOT NULL REFERENCES layer1_event_lifecycle(event_id), from_state TEXT,
 to_state TEXT NOT NULL, reason_code TEXT NOT NULL, evidence_refs_json JSONB NOT NULL,
 transitioned_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_layer1_event_transition_history ON layer1_event_transitions(event_id,transition_id);

CREATE TABLE IF NOT EXISTS layer1_research_package_versions (
 research_key TEXT NOT NULL, version INTEGER NOT NULL CHECK(version>0), package_id TEXT NOT NULL UNIQUE,
 package_hash TEXT NOT NULL, cutoff_at TIMESTAMPTZ NOT NULL, payload_json JSONB NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), PRIMARY KEY(research_key,version),
 UNIQUE(research_key,package_hash)
);
CREATE TABLE IF NOT EXISTS editorial_brief_versions (
 event_id TEXT NOT NULL, angle_id TEXT NOT NULL, version INTEGER NOT NULL CHECK(version>0),
 brief_id TEXT NOT NULL UNIQUE, research_package_id TEXT NOT NULL REFERENCES layer1_research_package_versions(package_id),
 brief_hash TEXT NOT NULL, payload_json JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(event_id,angle_id,version), UNIQUE(event_id,angle_id,brief_hash)
);
CREATE TABLE IF NOT EXISTS content_draft_versions (
 draft_key TEXT NOT NULL, version INTEGER NOT NULL CHECK(version>0), draft_id TEXT NOT NULL UNIQUE,
 asset_id TEXT NOT NULL, content_hash TEXT NOT NULL CHECK(content_hash ~ '^[0-9a-f]{64}$'),
 research_package_id TEXT NOT NULL REFERENCES layer1_research_package_versions(package_id),
 editorial_brief_id TEXT NOT NULL REFERENCES editorial_brief_versions(brief_id),
 approved_claim_ids_json JSONB NOT NULL, content TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(draft_key,version), UNIQUE(draft_key,content_hash)
);
CREATE INDEX IF NOT EXISTS idx_content_draft_asset_created ON content_draft_versions(asset_id,created_at DESC);
CREATE TABLE IF NOT EXISTS content_draft_validation_results (
 validation_id TEXT PRIMARY KEY, draft_hash TEXT NOT NULL CHECK(draft_hash ~ '^[0-9a-f]{64}$'),
 status TEXT NOT NULL CHECK(status IN ('PASS','NEEDS_REVISION','REJECT')),
 reasons_json JSONB NOT NULL, validation_version TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_draft_validation_latest ON content_draft_validation_results(draft_hash,created_at DESC,validation_id DESC);
CREATE TABLE IF NOT EXISTS visual_validation_results (
 validation_id TEXT PRIMARY KEY, draft_hash TEXT NOT NULL CHECK(draft_hash ~ '^[0-9a-f]{64}$'),
 image_hash TEXT NOT NULL CHECK(image_hash ~ '^[0-9a-f]{64}$'),
 status TEXT NOT NULL CHECK(status IN ('PASS','NEEDS_REVISION','REJECT')),
 reasons_json JSONB NOT NULL, validation_version TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(draft_hash,image_hash,validation_id)
);
CREATE INDEX IF NOT EXISTS idx_visual_validation_pair ON visual_validation_results(draft_hash,image_hash,created_at DESC,validation_id DESC);
CREATE TABLE IF NOT EXISTS image_generation_artifacts (
 artifact_id TEXT PRIMARY KEY, draft_hash TEXT NOT NULL CHECK(draft_hash ~ '^[0-9a-f]{64}$'),
 image_hash TEXT NOT NULL CHECK(image_hash ~ '^[0-9a-f]{64}$'), asset_id TEXT NOT NULL, symbol TEXT NOT NULL,
 provider TEXT NOT NULL, model TEXT NOT NULL, request_id TEXT, generated_at TIMESTAMPTZ NOT NULL,
 prompt_hash TEXT NOT NULL CHECK(prompt_hash ~ '^[0-9a-f]{64}$'), generation_parameters_json JSONB NOT NULL,
 source_image_hash TEXT NOT NULL CHECK(source_image_hash ~ '^[0-9a-f]{64}$'), image_path TEXT NOT NULL,
 metadata_json JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(draft_hash,image_hash)
);
CREATE TABLE IF NOT EXISTS opportunity_decisions (
 decision_id TEXT PRIMARY KEY CHECK(decision_id ~ '^[0-9a-f]{64}$'),
 research_package_id TEXT NOT NULL REFERENCES layer1_research_package_versions(package_id),
 state TEXT NOT NULL CHECK(state IN ('PROCEED','RESEARCH_MORE','DEFER','REJECT')),
 score DOUBLE PRECISION CHECK(score IS NULL OR (score>=0 AND score<=100)),
 reasons_json JSONB NOT NULL, policy_version TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 input_snapshot_json JSONB NOT NULL
);

CREATE TABLE IF NOT EXISTS publication_attempts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, idempotency_key TEXT NOT NULL UNIQUE,
 coin_symbol TEXT NOT NULL, content_hash TEXT NOT NULL CHECK(content_hash ~ '^[0-9a-f]{64}$'),
 status TEXT NOT NULL CHECK(status IN ('SUBMITTING','PUBLICATION_UNKNOWN','PUBLISHED_CONFIRMED','FAILED_CONFIRMED')),
 remote_post_id TEXT UNIQUE, share_link TEXT, http_status INTEGER, error TEXT,
 reconciliation_note TEXT, reconciliation_evidence TEXT, reconciled_by TEXT, reconciled_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(length(btrim(idempotency_key))>0)
);
CREATE INDEX IF NOT EXISTS idx_publication_attempts_symbol_status ON publication_attempts(coin_symbol,status);
CREATE TABLE IF NOT EXISTS publication_quota_reservations (
 reservation_id TEXT PRIMARY KEY, day_utc DATE NOT NULL, symbol TEXT NOT NULL,
 status TEXT NOT NULL CHECK(status IN ('RESERVED','SUBMITTING','PUBLICATION_UNKNOWN','PUBLISHED_CONFIRMED','FAILED_CONFIRMED','RELEASED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 authorization_id TEXT, attempt_id BIGINT UNIQUE REFERENCES publication_attempts(id)
);
CREATE INDEX IF NOT EXISTS idx_publication_quota_day_status ON publication_quota_reservations(day_utc,status);
CREATE TABLE IF NOT EXISTS publication_authorizations (
 authorization_id TEXT PRIMARY KEY CHECK(authorization_id ~ '^[0-9a-f]{64}$'),
 draft_id TEXT NOT NULL REFERENCES content_draft_versions(draft_id),
 research_package_id TEXT NOT NULL REFERENCES layer1_research_package_versions(package_id),
 editorial_brief_id TEXT NOT NULL REFERENCES editorial_brief_versions(brief_id),
 event_id TEXT NOT NULL, asset_id TEXT NOT NULL,
 quota_reservation_id TEXT NOT NULL REFERENCES publication_quota_reservations(reservation_id),
 payload_json JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL, expires_at TIMESTAMPTZ NOT NULL,
 CHECK(expires_at>created_at)
);
CREATE INDEX IF NOT EXISTS idx_publication_authorization_expiry ON publication_authorizations(expires_at);
CREATE TABLE IF NOT EXISTS publication_reconciliation_events (
 reconciliation_id TEXT PRIMARY KEY, attempt_id BIGINT NOT NULL REFERENCES publication_attempts(id),
 prior_status TEXT NOT NULL, new_status TEXT NOT NULL, reconciled_by TEXT NOT NULL,
 evidence TEXT NOT NULL, note TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(length(btrim(reconciled_by))>0), CHECK(length(btrim(evidence))>0), CHECK(length(btrim(note))>0)
);
CREATE TABLE IF NOT EXISTS posts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 coin_symbol TEXT, content TEXT NOT NULL, metadata JSONB
);
CREATE TABLE IF NOT EXISTS post_analytics (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, post_id BIGINT REFERENCES posts(id) ON DELETE SET NULL,
 coin_symbol TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), remote_post_id TEXT,
 views BIGINT, likes BIGINT, comments BIGINT, shares BIGINT, eligible_traders BIGINT,
 reward_earned DOUBLE PRECISION, metrics_updated_at TIMESTAMPTZ, is_analyzed BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_post_analytics_symbol_created ON post_analytics(coin_symbol,created_at DESC);

CREATE TABLE IF NOT EXISTS metrics (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 post_id BIGINT REFERENCES posts(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 views BIGINT NOT NULL,
 traders BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS runs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 status TEXT NOT NULL,
 summary JSONB
);
